-- The schema of migrations/sqlite/0015_push_subscriptions.sql for PostgreSQL: the Web Push
-- subscriptions of the portal's Notifications.
CREATE TABLE push_subscriptions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    endpoint   TEXT   NOT NULL UNIQUE,
    p256dh     TEXT   NOT NULL,
    auth       TEXT   NOT NULL,
    label      TEXT   NOT NULL DEFAULT '',
    kinds      TEXT   NOT NULL,
    failures   BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    last_ok_at BIGINT
);

CREATE INDEX push_subscriptions_account ON push_subscriptions (account_id);
