-- The schema of migrations/sqlite/0001_init.sql for PostgreSQL. Both run the same queries
-- (docs/adr/0003-postgres-for-a-cluster.md), so every column has the same name and meaning.
-- IDs and times are BIGINT, bytes are BYTEA.

CREATE TABLE accounts (
    id         BIGINT PRIMARY KEY,
    handle     TEXT   NOT NULL,
    handle_key TEXT   NOT NULL UNIQUE,
    email      TEXT   NOT NULL UNIQUE,
    created    BIGINT NOT NULL
);

CREATE TABLE devices (
    id            BIGINT PRIMARY KEY,
    account_id    BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    name          TEXT   NOT NULL,
    platform      TEXT   NOT NULL,
    refresh_hash  BYTEA  NOT NULL UNIQUE,
    created       BIGINT NOT NULL,
    last_used     BIGINT NOT NULL
);

CREATE INDEX devices_account ON devices (account_id);

-- One row per friendship, with the lower account ID in `low`.
CREATE TABLE friends (
    low   BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    high  BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    since BIGINT NOT NULL,
    PRIMARY KEY (low, high),
    CHECK (low < high)
);

CREATE INDEX friends_high ON friends (high);

CREATE TABLE friend_requests (
    from_id BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    to_id   BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    since   BIGINT NOT NULL,
    PRIMARY KEY (from_id, to_id)
);

CREATE INDEX friend_requests_to ON friend_requests (to_id);

CREATE TABLE blocks (
    blocker BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    blocked BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    since   BIGINT NOT NULL,
    PRIMARY KEY (blocker, blocked)
);

CREATE INDEX blocks_blocked ON blocks (blocked);

CREATE TABLE reports (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    reported BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    reason   TEXT   NOT NULL,
    details  TEXT   NOT NULL,
    created  BIGINT NOT NULL
);

CREATE INDEX reports_reporter ON reports (reporter, created);
CREATE INDEX reports_reported ON reports (reported);

-- A ban outlives its account: it is kept when the account is deleted, and the hash of the e-mail
-- address stops the same person from signing up again with it. `until` is null for good.
CREATE TABLE bans (
    account_id BIGINT PRIMARY KEY,
    email_hash BYTEA  NOT NULL,
    until      BIGINT,
    reason     TEXT   NOT NULL,
    created    BIGINT NOT NULL
);

CREATE INDEX bans_email ON bans (email_hash);

-- Refresh tokens that were replaced, so that one coming back is noticed. Only recent ones are
-- kept: an old token is useless anyway, and the table must not grow without bound.
CREATE TABLE used_refresh (
    hash      BYTEA  PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    used      BIGINT NOT NULL
);

CREATE INDEX used_refresh_device ON used_refresh (device_id, used);
